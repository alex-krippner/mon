tasks.register("generateIconCatalog") {
    val vectorsRoot =
        project.projectDir.resolve("src/commonMain/kotlin/com/akrippner/mon/core/designsystem/icon/defaultIcons")
    val outTokensDir =
        project.projectDir.resolve("src/commonMain/kotlin/com/akrippner/mon/core/designsystem/icon")

    val outCatalogDir =
        project.projectDir.resolve("src/commonMain/kotlin/com/akrippner/mon/core/designsystem/icon/defaultIcons")

    inputs.dir(vectorsRoot)
    outputs.dir(outTokensDir)
    outputs.dir(outCatalogDir)

    doLast {
        val categoryToIcons = linkedMapOf<String, MutableSet<String>>()
        val iconUsesSecondaryColor = mutableMapOf<String, Boolean>()

        vectorsRoot
            .walkTopDown()
            .filter { it.isFile && it.extension == "kt" }
            .forEach { file ->
                val text = file.readText()
                val valRegex =
                    Regex("""val\s+Icons\.(\w+)\.([A-Z][A-Za-z0-9_]*)\s*:\s*ImageVector""")
                val funRegex = Regex(
                    """fun\s+Icons\.(\w+)\.([A-Z][A-Za-z0-9_]*)\s*\([\s\S]*?\)\s*:\s*ImageVector""",
                    RegexOption.MULTILINE
                )

                valRegex.findAll(text).forEach { m ->
                    val category = m.groupValues[1]
                    val iconName = m.groupValues[2]
                    val key = "$category/$iconName"
                    categoryToIcons.getOrPut(category) { linkedSetOf() }.add(iconName)
                    iconUsesSecondaryColor[key] = text.contains("secondaryColor: Color")
                }

                funRegex.findAll(text).forEach { m ->
                    val category = m.groupValues[1]
                    val iconName = m.groupValues[2]
                    val key = "$category/$iconName"
                    categoryToIcons.getOrPut(category) { linkedSetOf() }.add(iconName)
                    iconUsesSecondaryColor[key] = text.contains("secondaryColor: Color")
                }
            }
        categoryToIcons.replaceAll { _, v -> v.toMutableList().sorted().toMutableSet() }
        // --- Generate Icon tokens (Icon.Core.Add) ---
        run {
            outTokensDir.mkdirs()
            val tokensFile = outTokensDir.resolve("IconIds.generated.kt")
            val content = buildString {
                appendLine("package com.akrippner.mon.core.designsystem.icon")
                appendLine()
                appendLine("// Auto-generated by generateIconCatalog. Do not edit manually.")
                appendLine("// Source: ImageVector extensions under com.akrippner.mon.core.designsystem.icon.defaultIcons")
                appendLine()
                appendLine("import androidx.compose.runtime.Immutable")
                appendLine()
                appendLine("@Immutable")
                appendLine("sealed interface IconId { val category: String; val name: String }")
                appendLine("private data class IconIdImpl(override val category: String, override val name: String) : IconId")
                appendLine()
                appendLine("object Icon {")
                categoryToIcons.forEach { (category, _) ->
                    appendLine(" object $category {")
                    categoryToIcons[category]?.forEach { icon ->
                        appendLine("  val $icon: IconId = IconIdImpl(\"$category\", \"$icon\")")
                    }
                    appendLine(" }")
                }
                appendLine("}")
            }
            tokensFile.writeText(content)
        }

        // --- Generate Catalog with open properties per icon and get() mapper ---
        run {
            outCatalogDir.mkdirs()
            val catalogFile = outCatalogDir.resolve("IconCatalog.generated.kt")
            val content = buildString {
                appendLine("package com.akrippner.mon.core.designsystem.icon.defaultIcons")
                appendLine()
                appendLine("// Auto-generated by generateIconCatalog. Do not edit manually.")
                appendLine("import androidx.compose.runtime.Immutable")
                appendLine("import androidx.compose.ui.graphics.Color")
                appendLine("import androidx.compose.ui.graphics.vector.ImageVector")
                appendLine("import com.akrippner.mon.core.designsystem.icon.IconId")
                appendLine("import com.akrippner.mon.core.designsystem.icon.Icon")
                appendLine()
                categoryToIcons.forEach { (category, icons) ->
                    appendLine("import com.akrippner.mon.core.designsystem.icon.defaultIcons.${category.lowercase()}.*")
                }
                appendLine()
                appendLine("@Immutable")
                appendLine("abstract class IconCatalog {")
                categoryToIcons.forEach { (category, icons) ->
                    icons.forEach { icon ->
                        val prop = (category + icon).replaceFirstChar { it.lowercase() }
                        val key = "$category.$icon"
                        val usesSecondary = iconUsesSecondaryColor[key] ?: false

                        if (usesSecondary) {
                            appendLine(
                                "open fun $prop(primaryColor: Color = Color(0xFF000000), secondaryColor: Color = Color(0xFFDADADA)): ImageVector = Icons.$category.$icon(primaryColor, secondaryColor)"
                            )
                        } else {
                            appendLine(" open fun $prop(primaryColor: Color = Color(0xFF000000)): ImageVector = Icons.$category.$icon(primaryColor)")
                        }
                    }
                }
                appendLine()
                appendLine(
                    " open fun get(id: IconId, primaryColor: Color = Color(0xFF000000), secondaryColor: Color = Color(0xFFDADADA)): ImageVector = when (id) {"
                )
                categoryToIcons.forEach { (category, icons) ->
                    icons.forEach { icon ->
                        val prop = (category + icon).replaceFirstChar { it.lowercase() }
                        val key = "$category.$icon"
                        val usesSecondary = iconUsesSecondaryColor[key] ?: false

                        if (usesSecondary) {
                            appendLine(" Icon.$category.$icon -> $prop(primaryColor, secondaryColor)")
                        } else {
                            appendLine(" Icon.$category.$icon -> $prop(primaryColor)")
                        }
                    }
                }
                appendLine(" else -> error(\"Unknown icon: ${'$'}{id.category}:${'$'}{id.name}\")")
                appendLine(" }")
                appendLine("}")
                appendLine()
                appendLine("object DefaultIconCatalog : IconCatalog()")
            }
            catalogFile.writeText(content)
        }
    }
}

